const LangContext = createContext({ lang: 'tr', setLang: () => {}, t: (k) => k })

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try { return localStorage.getItem('tesbihat.lang') || 'tr' } catch { return 'tr' }
  })
  useEffect(() => {
    try {
      document.documentElement.lang = lang
      document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr'
    } catch { /* yoksay */ }
  }, [lang])
  const setLang = useCallback((l) => {
    setLangState(l)
    try { localStorage.setItem('tesbihat.lang', l) } catch { /* yoksay */ }
  }, [])
  const t = useCallback((key, vars) => {
    const dict = UI[lang] ?? UI.tr
    let s = dict[key] ?? UI.tr[key] ?? key
    if (vars) for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(String(vars[k]))
    return s
  }, [lang])
  return React.createElement(LangContext.Provider, { value: { lang, setLang, t } }, children)
}

export function useLang() {
  return useContext(LangContext)
}

export function tStatic(key, vars) {
  let lang = 'tr'
  try { lang = localStorage.getItem('tesbihat.lang') || 'tr' } catch { /* yoksay */ }
  const dict = UI[lang] ?? UI.tr
  let s = dict[key] ?? UI.tr[key] ?? key
  if (vars) for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(String(vars[k]))
  return s
}
