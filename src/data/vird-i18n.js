// Bir adım nesnesini (title/meaning/note/endNote) hedef dile çevirir; eksik anahtarda
// adımın mevcut (TR) metni korunur. Arapça ve latin metinlere dokunulmaz.
export function localizeStep(step, lang) {
  if (!lang || lang === 'tr' || !step) return step
  const pack = VIRD_I18N[lang]
  if (!pack) return step
  const o = pack.steps?.[step.id]
  const out = { ...step }
  if (o) {
    if (o.title) out.title = o.title
    if (o.meaning) out.meaning = o.meaning
    if (o.note) out.note = o.note
    if (o.endNote && step.endNote) out.endNote = { ...step.endNote, ...o.endNote }
  }
  // endNote (rızık duası) adım id'si farklı olabilir; id üzerinden rizik paketi de dene
  if (!o && step.id === 'rizik-duasi' && pack.rizik) {
    out.title = pack.rizik.title ?? out.title
    out.meaning = pack.rizik.meaning ?? out.meaning
    if (step.endNote) out.endNote = { ...step.endNote, ...pack.rizik.endNote }
  }
  return out
}

export function localizedRizik(base, lang) {
  if (!lang || lang === 'tr') return base
  const pack = VIRD_I18N[lang]?.rizik
  if (!pack) return base
  return {
    ...base,
    title: pack.title ?? base.title,
    meaning: pack.meaning ?? base.meaning,
    endNote: base.endNote ? { ...base.endNote, ...pack.endNote } : base.endNote,
  }
}

export function localizedHizbMeaning(lang) {
  if (!lang || lang === 'tr') return null
  return VIRD_I18N[lang]?.hizbMeaning ?? null
}

export function localizedDuaNotes(lang) {
  if (!lang || lang === 'tr') return null
  return VIRD_I18N[lang]?.duaNotes ?? null
}
